# 【为什么"把 kd 调回旧值"这条路走不通】
#   D 项 = kd_eff * omega，输出 clamp 到 +-1.0，于是
#       阻尼能力上限  <=>  kd_eff * omega_peak <= 1.0
#   旧载具 omega_peak=0.21 => kd_eff 可用到 4.68（zeta 0.98，实飞临界阻尼）
#   本载具 omega_peak=0.96 => kd_eff 只能到 1.0 => zeta 最高 0.21
