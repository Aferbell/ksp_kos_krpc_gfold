def vz_gate_max(alt, vh=0.0):
    """给定 (高度, 横速) 处的可解垂速上限 [m/s]。

    【为什么必须随高度变化，不能用一个常数】
      交班后是【无油门滑行】，vz 只增不减。以末条 handoff 实测为例
      （alt=665.9 vz=65.3，g=9.81）：
          alt=640 -> vz=69.1      alt=600 -> vz=74.5
          alt=560 -> vz=79.6      alt=517 -> vz=84.8
      而 517 m 处的可解上限只有 80 —— 用常数 100 会在 500 m 判"门已满足"，
      实际已超限，P3 直接 infeasible。
    【为什么还随横速变化】
      横速越大，制动余量越少。扫描结果（vh=10 / 40 / 80 三列）：
          alt=517   80 / 70 / 50
          alt=540   90 / 80 / 50
          alt=600   90 / 80 / 60
          alt=640  100 / 90 / 60
          alt=667  100 / 90 / 70
      GATE_VH_MAX 已把 vh 限在 60 以下，这里按 vh=40 那一列再打 5 m/s 余量，
      即对上表的"中列"，比 vh=10 列保守、比 vh=80 列宽松 —— 因为
      交班实测 vh 就在 10~30 之间。
    """
    alt = float(alt)
    vh = max(0.0, float(vh))
    base = 80.0
    for lim, v in _VZ_TABLE:
        if alt >= lim:
            base = v
        else:
            break
    # 横速惩罚：每超 10 m/s 扣 2.5 m/s 垂速上限（对应扫描里 10->40 列掉 10）
    pen = max(0.0, vh - 10.0) / 30.0 * 10.0
    return max(50.0, base - pen)
