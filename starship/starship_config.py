def alpha_at_throttle(thr):
    """给定油门时的实测姿态角加速度 [deg/s^2]。

    原始拟合自 3 份实飞日志 428 个 (throttle, alpha_max) 样本【7 台】：
        alpha = 25.624*thr - 3.936   [deg/s^2]
    【2026-10-21】引擎 7 -> 13，推力乘 13/7，斜率同比缩放：
        alpha = 47.59*thr - 3.936    [deg/s^2]
    【为什么只缩斜率】万向节力矩 ∝ 推力 ∝ 引擎数；截距是反作用轮+气动，
      与引擎数无关。
    【thr 下界】拟合会给出负值（不可能），说明该区间万向节已无可偏转余量，
      只剩反作用轮。此处夹到 0.5 deg/s^2。
    """
    return max(0.5, 47.59 * float(thr) - 3.936)


def slew_max_deg(thr, headroom_deg=None):
    """给定油门时的【姿态参考最大角速率】[deg/s]。

    物理判据：slew_max = sqrt(2*alpha*headroom)
      物理意义：从静止加速到 slew、再同等减速停住，总角行程 = headroom。
    实测（headroom=45deg）：
        thr=0.55(悬停) alpha=10.2 -> 30.2 deg/s
        thr=1.00       alpha=21.7 -> 44.2 deg/s
    """
    _h = 45.0 if headroom_deg is None else float(headroom_deg)
    _a = alpha_at_throttle(thr)
    return math.degrees(math.sqrt(2.0 * math.radians(_a)
                                  * math.radians(_h)))

